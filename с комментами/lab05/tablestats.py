#чтение строк c csv 
def read_rows(lines: list[str]) -> list[dict]:
    rows = []
    #заголовки
    header = []

    #перебираем файл
    for line in lines:
        #strip() -- убирает пробелы
        line = line.strip()
        #если строка пустая (т. е line = ""), то переходим к следующей
        if not line:
            continue

        #создаем генератор списка. Перебираем значение в line.split(",") (split(",") -- разделить строку по  разделителю ",")
        #К каждому значению применяем .strip (на всякий), получаем список значений.
        f = [value.strip() for value in line.split(",")]

        #Если заголовок пустой, значит это первая непустая строка, заполняем его. Если он не пустой, условие не выполнится
        if not header:
            header = f
            #продолжаем с следующей строки
            continue
        #Если длина f (нашего ряда) не совпадает с длиной заголовка, значит заполнены не все столбцы. По условию такая строка не подходит
        if len(f) != len(header):
            continue

        #заполняем массив строк (dict(zip) -- автоматически создает словарь с ключами из header и значениями из f). Итог: rows список строк с словарями внутри
        rows.append(dict(zip(header, f)))

    #возвращаем массив строк
    return rows


#подсчет каждого из типов
def count_types(rows: list[dict]) -> dict:
    counts = {}
    for row in rows:
        #получаем значение ключа "тип"
        kind = row.get("тип", None)
        #Меняем значение counts[kind], т. е количество определенного типа, получая количество по get(kind), в случае отсутствия такого ключа,
        #он создается с значением "1"
        counts[kind] = counts.get(kind, 0) + 1
    return counts


#Подсчет кол-ва минут выполнения определенного типа
def total_minutes(rows: list[dict], kind: str) -> float:
    t = 0.0
    for row in rows:
        #получаем значение типа, если оно не совпадает с нужным нам (переменная kind), то идем к следующей строке
        if row.get('тип', None) != kind:
            continue
        try:
            #получаем кол-во минут. Здесь get лучше не использовать, т. к тесты на платформе могут прислать csv с "." вместо ",".
            #в питон у float используется точка, поэтому после получения значения row["минуты"] нужно заменить все запятые на точки, а потом уже делать перевод во float
            minutes =  float(row['минуты'].replace(",", "."))
        except ValueError:
            continue
        #добавляем к переменной времени
        t += minutes
    #округляем до десятых (по условию)
    return round(t, 1)


#создание строк для записи в csv
def to_csv(counts: dict) -> str:
    #по условию заголовок должен быть такой, поэтому это просто хардкод заголовка
    lines = ["тип,количество"]
    #перебираем типы в сортированном масиве значений counts, т. к по условию задачи запись в файл должна быть по алфавиту
    for kind in sorted(counts):
        #записываем в список элемент, где kind -- это название типа, а counts[kind] -- его кол-во
        #Пример: "ошибка,5"
        lines.append(f"{kind},{counts[kind]}")
    #'\n'.join(lines) -- создает строку, где каждый новый элемент из списка lines добавляется к строке с "\n", в конце добавлять "\n" необязательно
    return "\n".join(lines) + "\n"
